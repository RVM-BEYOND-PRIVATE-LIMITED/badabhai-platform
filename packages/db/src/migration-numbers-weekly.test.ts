/**
 * Migration `numbers_weekly` — the numbers screen's weekly snapshot and its recompute log (#2755
 * part B).
 *
 * The drizzle model and CI's drift check cover the table-vs-model half. What this file pins is the
 * half they do not see:
 *
 *   1. ADDITIVE — two new tables, no index beyond their keys, no foreign key. Nothing dropped, no
 *      existing table altered, no row written.
 *   2. THE RLS TAIL — FORCE and the four REVOKEs per table are hand-appended; a regenerate drops
 *      them.
 *   3. THE SNAPSHOT'S SHAPE — one row per week × metric × city group × trade group (the primary
 *      key), a week named by its Monday, a suppressed cell holding no number.
 *   4. THE LOG — a closed actor, a bounded reason in the operator's words, weeks in order.
 *   5. AGGREGATES ONLY — no worker, company, posting or order id column in the snapshot.
 *   6. THE HEADER — deploy order (before the SWITCH), the 42P01 behaviour, the lock and the
 *      rollback, and no number of its own.
 *
 * NUMBER-AGNOSTIC ON PURPOSE. The slot is still moving (it is regenerated by merge order before
 * merge), so the file is found by its tag SUFFIX in the journal rather than by a number, and this
 * test keeps passing across that regenerate. The hand-written header and tail carry no number for
 * the same reason.
 *
 * Nothing here connects to a database — it reads the committed SQL, journal and snapshot.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { SCHEMA_REQUIREMENTS } from "./schema-contract";
import { NUMBERS_RECOMPUTE_ACTORS, NUMBERS_RECOMPUTE_REASON_MAX } from "./schema/numbers-weekly";

const SUFFIX = "_numbers_weekly";
const SNAPSHOT_TABLE = "numbers_weekly";
const LOG_TABLE = "numbers_recompute_log";
const TABLES = [SNAPSHOT_TABLE, LOG_TABLE] as const;

const JOURNAL = JSON.parse(
  readFileSync(join(__dirname, "..", "migrations", "meta", "_journal.json"), "utf8"),
) as { entries: { idx: number; when: number; tag: string }[] };

const AT = JOURNAL.entries.findIndex((e) => e.tag.endsWith(SUFFIX));
const ENTRY = JOURNAL.entries[AT];
const TAG = ENTRY?.tag ?? "";
const NUMBER = TAG.slice(0, 4);
const RAW = readFileSync(join(__dirname, "..", "migrations", `${TAG}.sql`), "utf8");
/** Statements with comments stripped, so the header's prose cannot satisfy a DDL assertion. */
const DDL = RAW.replace(/--[^\n]*/g, " ");
const FLAT = DDL.replace(/\s+/g, " ");

const snapshot = (n: string): { id: string; prevId: string; tables: Record<string, unknown> } =>
  JSON.parse(
    readFileSync(join(__dirname, "..", "migrations", "meta", `${n}_snapshot.json`), "utf8"),
  );

/** The body of one CREATE TABLE, up to its closing `);`. */
function tableBody(table: string): string {
  const head = `CREATE TABLE "${table}" (`;
  const start = FLAT.indexOf(head);
  if (start < 0) throw new Error(`${table} not found`);
  const end = FLAT.indexOf(");", start);
  return FLAT.slice(start + head.length, end);
}

describe("the fixture is real (no assertion below is vacuous)", () => {
  it("finds exactly one journal entry with the tag suffix, and reads its SQL", () => {
    expect(JOURNAL.entries.filter((e) => e.tag.endsWith(SUFFIX))).toHaveLength(1);
    expect(NUMBER).toMatch(/^\d{4}$/);
    for (const table of TABLES) expect(FLAT).toContain(`CREATE TABLE "${table}"`);
  });

  it("strips the header, so prose cannot satisfy a DDL assertion", () => {
    expect(RAW).toContain("APPLY BEFORE THE SWITCH");
    expect(DDL).not.toContain("APPLY BEFORE THE SWITCH");
  });
});

describe("the migration is additive", () => {
  it("creates exactly the two tables, no index and no foreign key", () => {
    expect([...FLAT.matchAll(/CREATE TABLE/g)]).toHaveLength(2);
    expect(FLAT).not.toMatch(/CREATE (UNIQUE )?INDEX/);
    expect(FLAT).not.toContain("FOREIGN KEY");
    expect(FLAT).not.toContain("REFERENCES");
  });

  it("alters only the new tables", () => {
    const altered = [...FLAT.matchAll(/ALTER TABLE "([a-z_]+)"/g)].map((m) => m[1]);
    expect(new Set(altered)).toEqual(new Set(TABLES));
  });

  it("drops nothing, deletes nothing, writes no rows, and never touches the ledger", () => {
    for (const verb of [
      "DROP TABLE",
      "DROP COLUMN",
      "DROP CONSTRAINT",
      "DROP INDEX",
      "TRUNCATE",
      "DELETE FROM",
      "INSERT INTO",
      'UPDATE "',
    ]) {
      expect(FLAT.toUpperCase()).not.toContain(verb);
    }
    expect(FLAT).not.toContain("__drizzle_migrations");
  });
});

describe("deny by default", () => {
  it("enables AND forces RLS on both tables, and revokes every client role — no policy", () => {
    for (const table of TABLES) {
      expect(FLAT).toContain(`ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY`);
      expect(FLAT).toContain(`ALTER TABLE "${table}" FORCE ROW LEVEL SECURITY`);
      for (const role of ["PUBLIC", "anon", "authenticated", "service_role"]) {
        expect(FLAT).toContain(`REVOKE ALL ON TABLE "${table}" FROM ${role}`);
      }
    }
    expect(FLAT.toUpperCase()).not.toContain("CREATE POLICY");
    expect(FLAT.toUpperCase()).not.toContain("GRANT ");
  });

  it("is registered for its locks in schema-contract.ts, under this file's tag", () => {
    expect(SCHEMA_REQUIREMENTS.find((r) => r.id === `${NUMBER}-numbers-weekly-rls`)).toMatchObject({
      migration: TAG,
      kind: "rls",
      table: SNAPSHOT_TABLE,
    });
    expect(
      SCHEMA_REQUIREMENTS.find((r) => r.id === `${NUMBER}-numbers-recompute-log-rls`),
    ).toMatchObject({ migration: TAG, kind: "rls", table: LOG_TABLE });
  });
});

describe("the snapshot table", () => {
  const body = tableBody(SNAPSHOT_TABLE);

  it("is keyed one row per week × metric × city group × trade group", () => {
    expect(body).toContain(
      'CONSTRAINT "numbers_weekly_pkey" PRIMARY KEY("week_start","metric","city_group","trade_group")',
    );
    for (const col of ["week_start", "metric", "city_group", "trade_group"]) {
      expect(body).toMatch(new RegExp(`"${col}" (date|text) NOT NULL`));
    }
  });

  it("holds the figure, the two ratio terms, the suppression mark, the version and the freeze", () => {
    expect(body).toContain('"value" bigint,');
    expect(body).toContain('"numerator" bigint,');
    expect(body).toContain('"denominator" bigint,');
    expect(body).toContain('"suppressed" boolean DEFAULT false NOT NULL');
    expect(body).toContain('"definition_version" integer NOT NULL');
    expect(body).toContain('"computed_at" timestamp with time zone NOT NULL');
    expect(body).toContain('"frozen_at" timestamp with time zone,');
  });

  it("names every week by its Monday, and keeps a suppressed cell empty", () => {
    expect(body).toContain(`CHECK (extract(isodow from "numbers_weekly"."week_start") = 1)`);
    expect(body).toContain(
      'CHECK (NOT "numbers_weekly"."suppressed" OR ("numbers_weekly"."value" IS NULL AND ' +
        '"numbers_weekly"."numerator" IS NULL AND "numbers_weekly"."denominator" IS NULL))',
    );
  });

  it("carries aggregates only: no person, company, posting or order id, and no free text", () => {
    for (const column of ["worker_id", "payer_id", "posting_id", "order_id", "name", "phone"]) {
      expect(body, column).not.toContain(`"${column}"`);
    }
    expect(body).not.toContain("jsonb");
  });
});

describe("the recompute log", () => {
  const body = tableBody(LOG_TABLE);

  it("admits exactly its closed actors", () => {
    expect([...NUMBERS_RECOMPUTE_ACTORS]).toEqual(["cli"]);
    expect(body).toContain(`CHECK ("numbers_recompute_log"."actor" IN ('cli'))`);
  });

  it("bounds the operator's reason to 1..500 characters and keeps the weeks in order", () => {
    expect(NUMBERS_RECOMPUTE_REASON_MAX).toBe(500);
    expect(body).toContain('"reason" text NOT NULL');
    expect(body).toContain(
      `CHECK (char_length("numbers_recompute_log"."reason") BETWEEN 1 AND 500)`,
    );
    expect(body).toContain(
      'CHECK ("numbers_recompute_log"."from_week" <= "numbers_recompute_log"."to_week")',
    );
    expect(body).toContain('CHECK ("numbers_recompute_log"."rows_changed" >= 0)');
  });
});

describe("the header", () => {
  it("states the switch, the slot order, the 42P01 fail-closed read, the lock and the rollback", () => {
    expect(RAW).toContain("ADMIN_NUMBERS_ENABLED");
    expect(RAW).toContain("Apply every lower-numbered migration first");
    expect(RAW).toContain("42P01");
    expect(RAW).toContain("lock_timeout");
    expect(RAW).toContain("55P03");
    for (const table of TABLES) expect(RAW).toContain(`DROP TABLE "${table}";`);
  });

  it("names no migration number of its own, so a regenerate keeps it word for word", () => {
    const start = RAW.indexOf(`CREATE TABLE "${LOG_TABLE}"`);
    expect(start).toBeGreaterThan(0);
    expect(RAW.slice(0, start)).not.toContain(NUMBER);
    // …and neither does the hand-written tail.
    expect(RAW.slice(RAW.indexOf("DENY BY DEFAULT"))).not.toContain(NUMBER);
  });
});

describe("the journal and the snapshot", () => {
  it("records the entry after its predecessor, at its own idx, with a `when` above it", () => {
    expect(AT).toBeGreaterThan(0);
    const previous = JOURNAL.entries[AT - 1]!;
    expect(ENTRY!.idx).toBe(Number(NUMBER));
    expect(ENTRY!.idx).toBe(previous.idx + 1);
    expect(ENTRY!.when).toBeGreaterThan(previous.when);
  });

  it("its snapshot builds on its predecessor's and records both tables", () => {
    const next = snapshot(NUMBER);
    const previous = JOURNAL.entries[AT - 1]!.tag.slice(0, 4);
    expect(next.prevId).toBe(snapshot(previous).id);
    for (const table of TABLES) expect(next.tables).toHaveProperty(`public.${table}`);
  });
});
