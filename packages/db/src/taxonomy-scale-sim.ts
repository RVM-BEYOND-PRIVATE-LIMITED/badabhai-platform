/** What the planner actually did. Read from EXPLAIN — never inferred from index existence. */
export interface PlanFacts {
  hnswUsed: boolean;
  seqScan: boolean;
  planningMs: number;
  executionMs: number;
  actualRows: number;
  nodeTypes: string[];
  indexNames: string[];
}

/**
 * Walk an `EXPLAIN (ANALYZE, FORMAT JSON)` tree.
 *
 * `hnswUsed` requires BOTH an index-scan node AND that the index it names is the HNSW one.
 * A plan can use `skill_alias_skill_id_idx` and still sort every candidate by distance,
 * which is exact NN with extra steps — counting that as "the ANN engaged" would report the
 * caveat as resolved while it is still in force.
 */
export function readPlan(explain: unknown, hnswIndexName: string): PlanFacts {
  const root = Array.isArray(explain) ? (explain[0] as Record<string, unknown>) : (explain as Record<string, unknown>);
  const plan = root?.["Plan"] as Record<string, unknown> | undefined;
  const nodeTypes: string[] = [];
  const indexNames: string[] = [];
  let hnswUsed = false;
  let seqScan = false;

  const walk = (node: Record<string, unknown> | undefined): void => {
    if (!node) return;
    const type = String(node["Node Type"] ?? "");
    nodeTypes.push(type);
    if (type === "Seq Scan") seqScan = true;
    const indexName = node["Index Name"];
    if (typeof indexName === "string") {
      if (!indexNames.includes(indexName)) indexNames.push(indexName);
      if (indexName === hnswIndexName) hnswUsed = true;
    }
    for (const child of (node["Plans"] as Record<string, unknown>[] | undefined) ?? []) walk(child);
  };
  walk(plan);

  return {
    hnswUsed,
    seqScan,
    planningMs: Number(root?.["Planning Time"] ?? 0),
    executionMs: Number(root?.["Execution Time"] ?? 0),
    actualRows: Number(plan?.["Actual Rows"] ?? 0),
    nodeTypes,
    indexNames,
  };
}

/** Overlap of two ranked id lists — the ANN's recall against exact NN at the same depth. */
export function recallVsExact(ann: readonly string[], exact: readonly string[]): number | null {
  if (exact.length === 0) return null; // nothing to recall; 1.0 here would be a free pass
  const want = new Set(exact);
  return Math.round((ann.filter((id) => want.has(id)).length / exact.length) * 10_000) / 10_000;
}

