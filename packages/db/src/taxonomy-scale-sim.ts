/**
 * ANN scale simulation — what the retrieval QUERY does as the corpus grows toward
 * production size.
 *
 *   pnpm db:scale:taxonomy --plan                 # what would be built. Writes nothing.
 *   pnpm db:scale:taxonomy --run --sizes 1000,2000,5000,9121
 *   pnpm db:scale:taxonomy --teardown             # drop the sandbox schema
 *
 * ===========================================================================
 * WHAT THIS MEASURES, AND — MORE IMPORTANTLY — WHAT IT DOES NOT
 * ===========================================================================
 * The Phase 5 baseline reported Recall@1 99.1% over 197 real embeddings, and then had to
 * carry a caveat that swallowed the number: `EXPLAIN ANALYZE` showed a Seq Scan, so the
 * HNSW index was never consulted and the measurement was EXACT nearest-neighbour. Exact NN
 * is an upper bound. Nobody could say what happens when the index actually engages, because
 * 197 rows is far too few to make the planner choose it.
 *
 * This harness answers that, and only that. It measures INFRASTRUCTURE:
 *
 *   - is the HNSW index used at all, at each corpus size (read from the plan, never assumed)
 *   - planning time and execution time
 *   - how many rows survive the domain filter, versus the k that was asked for
 *   - how ef_search and iterative_scan move those numbers
 *   - how often a scoped query comes back EMPTY
 *   - ANN recall against exact NN — an index property, computed from ground truth this
 *     harness derives itself
 *
 * IT DOES NOT MEASURE RETRIEVAL QUALITY, and it cannot. The padding vectors are synthetic;
 * they carry no meaning, so "did the right skill come back" is not a question that has an
 * answer here. Every quality field in the experiment record it writes is null, and
 * `assertNoSemanticClaim` exists so a later change cannot quietly start filling them in.
 *
 * ===========================================================================
 * WHY THE PADDING IS PERTURBED REAL VECTORS, NOT RANDOM ONES
 * ===========================================================================
 * The obvious way to reach 9k rows is to generate uniform random unit vectors. It is also
 * useless, and quietly so. In 768 dimensions two random vectors are almost exactly
 * orthogonal, so random padding sits at cosine ~0 to every query: HNSW walks straight past
 * it to the real cluster and reports ~100% recall at every ef_search. The experiment would
 * conclude that the index is free, which is the opposite of what a dense corpus does.
 *
 * So padding is generated by perturbing a REAL corpus vector with Gaussian noise and
 * renormalizing. The noise scale controls how crowded the neighbourhood gets, and crowding
 * is precisely what makes an approximate search approximate. This produces a corpus with
 * realistic local density and no semantic content whatsoever — the right shape for an index
 * experiment and the wrong shape for a quality one, which is the trade this harness wants.
 *
 * The generator is SEEDED. An experiment nobody can re-run is an anecdote.
 *
 * ===========================================================================
 * IT CANNOT TOUCH THE REAL CORPUS
 * ===========================================================================
 * Everything lives in a dedicated `taxonomy_scale_sim` schema that the harness creates and
 * drops. There is no migration, so the tables cannot reach any other environment, and the
 * runner never issues a write against `public.skill_alias` — `--teardown` drops the sandbox
 * schema by name and nothing else. The Phase 5 embeddings are the input to this experiment;
 * destroying them to run it would be a poor trade.
 */
