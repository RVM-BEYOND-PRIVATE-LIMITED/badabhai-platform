/** The real taxonomy's shape, measured rather than guessed, so the padding matches it. */
export interface CorpusShape {
  aliasesPerSkill: number;
  skillsPerDomain: number;
  domainsPerSkill: number;
}

/**
 * How many synthetic skills and domains a target alias count implies.
 *
 * Derived from the MEASURED shape so the simulated corpus is the real one scaled up, not a
 * differently-shaped corpus of the same size. That distinction is load-bearing here: the
 * filtered-ANN behaviour this experiment is about depends on the SELECTIVITY of the domain
 * filter — how small a slice of the table one domain is — and selectivity is a function of
 * shape, not of row count. Padding with 9k aliases spread over 28 domains would make each
 * filter match a third of the table and show none of the pathology.
 */
export function planScale(targetAliases: number, realAliases: number, shape: CorpusShape): {
  syntheticAliases: number;
  syntheticSkills: number;
  syntheticDomains: number;
} {
  const syntheticAliases = Math.max(0, targetAliases - realAliases);
  const syntheticSkills = Math.max(1, Math.round(syntheticAliases / shape.aliasesPerSkill));
  // Each synthetic skill sits on `domainsPerSkill` edges, and each domain holds
  // `skillsPerDomain` of them.
  const syntheticDomains = Math.max(
    1,
    Math.round((syntheticSkills * shape.domainsPerSkill) / shape.skillsPerDomain),
  );
  return { syntheticAliases, syntheticSkills, syntheticDomains };
}

