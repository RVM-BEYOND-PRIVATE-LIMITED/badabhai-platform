/**
 * How similar a synthetic neighbour is to the real vector it was grown from.
 *
 * EXPRESSED AS A TARGET COSINE, NOT A NOISE SIGMA, and that is not cosmetic. Sigma is a
 * per-component quantity, so its effect depends on the dimensionality: at 768 dimensions a
 * unit vector's components are ~1/sqrt(768) ≈ 0.036, and a "small-sounding" sigma of 0.35
 * adds noise with norm 0.35*sqrt(768) ≈ 9.7 — ten times the signal, landing the result at
 * cosine 0.10, i.e. essentially ORTHOGONAL. That was the first value tried here and a test
 * caught it. It would have produced padding that competes with nothing, HNSW recall of
 * ~100% at every ef_search, and a confident conclusion that the index is free.
 *
 * 0.85 puts the padding in the band the real corpus shows between genuinely confusable
 * siblings — the Phase 5 diagnosis measured rank-1 hits at ~0.79-0.88 with competitors
 * 0.19-0.46 below. Crowding is what makes an approximate search approximate, so this is the
 * single most consequential knob in the harness. It is recorded in the experiment.
 */
export const DEFAULT_NEIGHBOUR_COSINE = 0.85;
/** A query is a PARAPHRASE of one alias, not a different alias — much closer than padding. */
export const DEFAULT_QUERY_COSINE = 0.95;

/**
 * The per-component sigma that lands `parent + noise` at `targetCosine` from `parent`.
 *
 * For a unit parent and isotropic noise of norm n, cos = 1/sqrt(1 + n^2); inverting gives
 * n = sqrt(1/c^2 - 1), and n = sigma*sqrt(dim) for independent per-component Gaussians.
 * Deriving it means the knob stays meaningful if the embedding width ever changes.
 */
export function sigmaForCosine(targetCosine: number, dim: number = EMBEDDING_DIMENSION): number {
  if (!(targetCosine > 0 && targetCosine < 1)) {
    throw new Error(`[scale] targetCosine must be in (0, 1), got ${targetCosine}`);
  }
  return Math.sqrt(1 / (targetCosine * targetCosine) - 1) / Math.sqrt(dim);
}

// ===========================================================================
// Deterministic vector synthesis
// ===========================================================================

/** mulberry32 — small, fast, and identical across platforms, which `Math.random` is not. */
export function makeRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Box-Muller. Two uniforms in, one standard normal out. */
export function gaussian(rng: () => number): number {
  // u must be non-zero: log(0) is -Infinity and would poison the whole vector.
  let u = 0;
  while (u === 0) u = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rng());
}

/**
 * A synthetic neighbour of `parent`: add Gaussian noise, then L2-normalize.
 *
 * Normalizing matters beyond tidiness — the real corpus is normalized by the ai-service, and
 * a padding set at a different magnitude would be trivially separable by cosine distance,
 * which is exactly the shortcut that would make the ANN look better than it is.
 */
export function perturb(parent: readonly number[], sigma: number, rng: () => number): number[] {
  const out = new Array<number>(parent.length);
  let norm = 0;
  for (let i = 0; i < parent.length; i += 1) {
    const v = (parent[i] as number) + gaussian(rng) * sigma;
    out[i] = v;
    norm += v * v;
  }
  norm = Math.sqrt(norm);
  if (norm === 0) throw new Error("[scale] perturbation produced a zero vector");
  for (let i = 0; i < out.length; i += 1) out[i] = (out[i] as number) / norm;
  return out;
}

export function cosine(a: readonly number[], b: readonly number[]): number {
  let dot = 0;
  let na = 0;
  let nb = 0;
  for (let i = 0; i < a.length; i += 1) {
    dot += (a[i] as number) * (b[i] as number);
    na += (a[i] as number) ** 2;
    nb += (b[i] as number) ** 2;
  }
  return dot / (Math.sqrt(na) * Math.sqrt(nb));
}

// ===========================================================================
// The corpus shape being simulated
