/**
 * Migration `credit_call_log` — the out-of-credits call log (#2755 part C).
 *
 * The drizzle model and CI's drift check cover the table-vs-model half. What this file pins is the
 * half they do not see:
 *
 *   1. ADDITIVE — one new table, its one index and its one foreign key. Nothing dropped, no
 *      existing table altered, no row written.
 *   2. THE RLS TAIL — FORCE and the four REVOKEs are hand-appended; a regenerate drops them.
 *   3. CLOSED CODES ONLY — the result CHECK spells exactly `CREDIT_CALL_RESULTS`, and the table has
 *      no free-text, name or phone column.
 *   4. THE CASCADE — the call log goes with the company.
 *   5. THE HEADER — deploy order (before the SWITCH), the 42P01 behaviour, the lock and the
 *      rollback, and no number of its own.
 *
 * NUMBER-AGNOSTIC ON PURPOSE. The slot is still moving (it is regenerated by merge order before
 * merge), so the file is found by its tag SUFFIX in the journal rather than by a number, and this
 * test keeps passing across that regenerate. The hand-written header and tail carry no number for
 * the same reason.
 *
 * Nothing here connects to a database — it reads the committed SQL, journal and snapshot.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { CREDIT_CALL_RESULTS } from "@badabhai/types";
import { describe, expect, it } from "vitest";

import { SCHEMA_REQUIREMENTS } from "./schema-contract";

const SUFFIX = "_credit_call_log";
const TABLE = "credit_call_log";

const JOURNAL = JSON.parse(
  readFileSync(join(__dirname, "..", "migrations", "meta", "_journal.json"), "utf8"),
) as { entries: { idx: number; when: number; tag: string }[] };

const AT = JOURNAL.entries.findIndex((e) => e.tag.endsWith(SUFFIX));
const ENTRY = JOURNAL.entries[AT];
const TAG = ENTRY?.tag ?? "";
const NUMBER = TAG.slice(0, 4);
const RAW = readFileSync(join(__dirname, "..", "migrations", `${TAG}.sql`), "utf8");
/** Statements with comments stripped, so the header's prose cannot satisfy a DDL assertion. */
const DDL = RAW.replace(/--[^\n]*/g, " ");
const FLAT = DDL.replace(/\s+/g, " ");

const snapshot = (n: string): { id: string; prevId: string; tables: Record<string, unknown> } =>
  JSON.parse(
    readFileSync(join(__dirname, "..", "migrations", "meta", `${n}_snapshot.json`), "utf8"),
  );

/** The body of the CREATE TABLE, up to its closing `);`. */
function tableBody(): string {
  const head = `CREATE TABLE "${TABLE}" (`;
  const start = FLAT.indexOf(head);
  if (start < 0) throw new Error(`${TABLE} not found`);
  return FLAT.slice(start + head.length, FLAT.indexOf(");", start));
}

describe("the fixture is real (no assertion below is vacuous)", () => {
  it("finds exactly one journal entry with the tag suffix, and reads its SQL", () => {
    expect(JOURNAL.entries.filter((e) => e.tag.endsWith(SUFFIX))).toHaveLength(1);
    expect(NUMBER).toMatch(/^\d{4}$/);
    expect(FLAT).toContain(`CREATE TABLE "${TABLE}"`);
  });

  it("strips the header, so prose cannot satisfy a DDL assertion", () => {
    expect(RAW).toContain("APPLY BEFORE THE SWITCH");
    expect(DDL).not.toContain("APPLY BEFORE THE SWITCH");
  });
});

describe("the migration is additive", () => {
  it("creates exactly the one table, its one index and its one foreign key", () => {
    expect([...FLAT.matchAll(/CREATE TABLE/g)]).toHaveLength(1);
    expect([...FLAT.matchAll(/CREATE (UNIQUE )?INDEX/g)]).toHaveLength(1);
    expect(FLAT).not.toContain("CREATE UNIQUE INDEX");
    expect([...FLAT.matchAll(/FOREIGN KEY/g)]).toHaveLength(1);
  });

  it("alters only the new table", () => {
    const altered = [...FLAT.matchAll(/ALTER TABLE "([a-z_]+)"/g)].map((m) => m[1]);
    expect(new Set(altered)).toEqual(new Set([TABLE]));
  });

  it("drops nothing, deletes nothing, writes no rows, and never touches the ledger", () => {
    for (const verb of [
      "DROP TABLE",
      "DROP COLUMN",
      "DROP CONSTRAINT",
      "DROP INDEX",
      "TRUNCATE",
      "DELETE FROM",
      "INSERT INTO",
      'UPDATE "',
    ]) {
      expect(FLAT.toUpperCase()).not.toContain(verb);
    }
    expect(FLAT).not.toContain("__drizzle_migrations");
  });
});

describe("deny by default", () => {
  it("enables AND forces RLS, and revokes every client role — no policy", () => {
    expect(FLAT).toContain(`ALTER TABLE "${TABLE}" ENABLE ROW LEVEL SECURITY`);
    expect(FLAT).toContain(`ALTER TABLE "${TABLE}" FORCE ROW LEVEL SECURITY`);
    for (const role of ["PUBLIC", "anon", "authenticated", "service_role"]) {
      expect(FLAT).toContain(`REVOKE ALL ON TABLE "${TABLE}" FROM ${role}`);
    }
    expect(FLAT.toUpperCase()).not.toContain("CREATE POLICY");
    expect(FLAT.toUpperCase()).not.toContain("GRANT ");
  });

  it("is registered for its lock in schema-contract.ts, under this file's tag", () => {
    expect(SCHEMA_REQUIREMENTS.find((r) => r.id === `${NUMBER}-credit-call-log-rls`)).toMatchObject(
      {
        migration: TAG,
        kind: "rls",
        table: TABLE,
      },
    );
  });
});

describe("the table", () => {
  const body = tableBody();

  it("holds the company, the admin, the time and the result, all NOT NULL", () => {
    expect(body).toContain('"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL');
    expect(body).toContain('"payer_id" uuid NOT NULL');
    expect(body).toContain('"called_by_admin_id" uuid NOT NULL');
    expect(body).toContain('"called_at" timestamp with time zone DEFAULT now() NOT NULL');
    expect(body).toContain('"result" text NOT NULL');
  });

  it("admits exactly the closed result codes of CREDIT_CALL_RESULTS", () => {
    expect([...CREDIT_CALL_RESULTS]).toEqual([
      "reached_will_buy",
      "reached_not_now",
      "reached_declined",
      "no_answer",
      "wrong_number",
    ]);
    const spelled = CREDIT_CALL_RESULTS.map((r) => `'${r}'`).join(", ");
    expect(body).toContain(
      `CONSTRAINT "credit_call_log_result_chk" CHECK ("credit_call_log"."result" IN (${spelled}))`,
    );
  });

  it("carries no free text: no note, name, phone, email or json column", () => {
    const columns = [
      ...body.matchAll(/"([a-z_]+)" (uuid|text|timestamp|integer|bigint|boolean|jsonb)/g),
    ].map((m) => m[1]);
    expect(columns.sort()).toEqual(["called_at", "called_by_admin_id", "id", "payer_id", "result"]);
    for (const forbidden of ["note", "name", "phone", "email", "comment"]) {
      expect(body, forbidden).not.toContain(forbidden);
    }
    expect(body).not.toContain("jsonb");
  });

  it("cascades with the company, and has no FK on the admin", () => {
    expect(FLAT).toContain(
      `ALTER TABLE "${TABLE}" ADD CONSTRAINT "credit_call_log_payer_id_payers_id_fk" FOREIGN KEY ("payer_id") REFERENCES "public"."payers"("id") ON DELETE cascade`,
    );
    expect(FLAT).not.toMatch(/FOREIGN KEY \("called_by_admin_id"\)/);
  });

  it("indexes the latest-call read: (payer_id, called_at DESC)", () => {
    expect(FLAT).toContain(
      `CREATE INDEX "credit_call_log_payer_called_idx" ON "${TABLE}" USING btree ("payer_id","called_at" DESC NULLS LAST)`,
    );
  });
});

describe("the header", () => {
  it("states the switch, the slot order, the 42P01 behaviour, the lock and the rollback", () => {
    expect(RAW).toContain("ADMIN_NUMBERS_ENABLED");
    expect(RAW).toContain("Apply every lower-numbered migration first");
    expect(RAW).toContain("42P01");
    expect(RAW).toContain("last_call: null");
    expect(RAW).toContain("lock_timeout");
    expect(RAW).toContain("55P03");
    expect(RAW).toContain(`DROP TABLE "${TABLE}";`);
  });

  it("names no migration number of its own, so a regenerate keeps it word for word", () => {
    const start = RAW.indexOf(`CREATE TABLE "${TABLE}"`);
    expect(start).toBeGreaterThan(0);
    expect(RAW.slice(0, start)).not.toContain(NUMBER);
    // …and neither does the hand-written tail.
    expect(RAW.slice(RAW.indexOf("DENY BY DEFAULT"))).not.toContain(NUMBER);
  });
});

describe("the journal and the snapshot", () => {
  it("records the entry after its predecessor, at its own idx, with a `when` above it", () => {
    expect(AT).toBeGreaterThan(0);
    const previous = JOURNAL.entries[AT - 1]!;
    expect(ENTRY!.idx).toBe(Number(NUMBER));
    expect(ENTRY!.idx).toBe(previous.idx + 1);
    expect(ENTRY!.when).toBeGreaterThan(previous.when);
  });

  it("its snapshot builds on its predecessor's and records the table", () => {
    const next = snapshot(NUMBER);
    const previous = JOURNAL.entries[AT - 1]!.tag.slice(0, 4);
    expect(next.prevId).toBe(snapshot(previous).id);
    expect(next.tables).toHaveProperty(`public.${TABLE}`);
  });
});
