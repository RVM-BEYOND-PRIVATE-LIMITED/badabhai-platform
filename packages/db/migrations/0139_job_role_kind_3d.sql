-- 0139 - widen role_kind CHECKs with the 22nd declared kind (CEO Launch Plan
-- Pack v1, Track A #4: 3D CAD Designer)
--
-- PURELY ADDITIVE at the vocabulary level: DROP + ADD of the two NULL-tolerant
-- CHECKs, each re-closing the same list plus 'cad_designer_3d'. No column is
-- added, dropped or rewritten; no backfill. The model-level tripwire in
-- `migration-0131-job-role-kind.test.ts` reads the drizzle model and stays red
-- until both constraints name the new kind — this migration is the change that
-- turns it green.
--
-- PRIVACY: a closed enum of occupation slugs. No employer identity, no worker identity.
--
-- APPLY-BEFORE-DEPLOY. The payer portal renders the role picker from
-- `JOB_ROLE_LABELS` (which gains `cad_designer_3d` in the same change), so a
-- build carrying the new label against a database without the widened CHECK 500s
-- the posting the moment a payer picks the new role ("violates check
-- constraint"). An OLD build on a migrated database is fine (a superset). No new
-- schema-contract entries: the checked objects (columns and named CHECKs) are the
-- 0131 ones, already registered — this migration only widens their definitions.
--
-- LOCKS. Each validated `ADD CONSTRAINT ... CHECK` takes ACCESS EXCLUSIVE and
-- scans its table under it; over a `role_kind` column that is NULL on almost
-- every row the predicate is trivially true and both tables are small, so the
-- scan is milliseconds. The real risk is QUEUEING (the 0131 precedent): wrap
-- all four statements in ONE `BEGIN; SET LOCAL lock_timeout = '3s'; ... COMMIT;`
-- and retry on 55P03. `db:migrate` applies every pending file in one transaction,
-- so set a session `lock_timeout` there too.
--
-- ROLLBACK. A CODE rollback needs no schema change: an older build never names the
-- new kind, and the widened CHECKs accept everything the old ones did. A schema
-- rollback REJECTS every stored 'cad_designer_3d' pick, so only on a database where
--   SELECT (SELECT count(*) FROM "job_postings" WHERE "role_kind" = 'cad_designer_3d')
--        + (SELECT count(*) FROM "jobs" WHERE "role_kind" = 'cad_designer_3d');   -- expect 0
-- and only AFTER the code that names the kind is rolled back:
--   ALTER TABLE "jobs" DROP CONSTRAINT "jobs_role_kind_chk";
--   ALTER TABLE "job_postings" DROP CONSTRAINT "job_postings_role_kind_chk";
--   -- then re-run the 0131 file's two ADD CONSTRAINT statements to restore the 21-kind lists.
-- ===========================================================================
ALTER TABLE "job_postings" DROP CONSTRAINT "job_postings_role_kind_chk";--> statement-breakpoint
ALTER TABLE "jobs" DROP CONSTRAINT "jobs_role_kind_chk";--> statement-breakpoint
ALTER TABLE "job_postings" ADD CONSTRAINT "job_postings_role_kind_chk" CHECK ("job_postings"."role_kind" IS NULL OR "job_postings"."role_kind" IN ('cnc_turner', 'vmc_milling', 'cnc_grinding', 'cam_programmer', 'cad_draughtsman', 'conventional_machinist', 'tool_die_maker', 'welder', 'sheet_metal_worker', 'press_operator', 'painter_coating', 'fitter', 'maintenance_technician', 'industrial_electrician', 'assembly_line_worker', 'quality_inspector', 'injection_moulding_operator', 'mould_die_maker', 'blow_moulding_operator', 'rubber_moulding_operator', 'plastic_process_technician', 'cad_designer_3d'));--> statement-breakpoint
ALTER TABLE "jobs" ADD CONSTRAINT "jobs_role_kind_chk" CHECK ("jobs"."role_kind" IS NULL OR "jobs"."role_kind" IN ('cnc_turner', 'vmc_milling', 'cnc_grinding', 'cam_programmer', 'cad_draughtsman', 'conventional_machinist', 'tool_die_maker', 'welder', 'sheet_metal_worker', 'press_operator', 'painter_coating', 'fitter', 'maintenance_technician', 'industrial_electrician', 'assembly_line_worker', 'quality_inspector', 'injection_moulding_operator', 'mould_die_maker', 'blow_moulding_operator', 'rubber_moulding_operator', 'plastic_process_technician', 'cad_designer_3d'));