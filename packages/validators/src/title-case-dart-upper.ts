const DART_VM_UPPER: ReadonlyMap<number, number> = (() => {
  const map = new Map<number, number>();
  for (const [first, last, delta, step] of DART_VM_UPPER_RUNS) {
    for (let cp = first; cp <= last; cp += step) map.set(cp, cp + delta);
  }
  return map;
})();

/** The Dart VM's `toUpperCase()` of a single code point; the code point itself when it has none. */
export function dartVmUpperCase(codePoint: number): number {
  return DART_VM_UPPER.get(codePoint) ?? codePoint;
}
