/**
 * The 60-trade catalogue (#2998) — the ONE statement of each trade.
 *
 * A trade is wired in about 14 hand-kept lists across 5 packages, and adding one
 * once touched eleven tables "none of which knows the others exist"
 * (`role-form-descriptor.ts`). This file is the statement every list is checked
 * against; the lists themselves stay where they are. Three tests hold them to it:
 * the consistency test in this package, the API parity test in `apps/api`, and
 * the DB parity test in `packages/db`.
 *
 * SOURCE. The CEO pack is the source for every trade name, ladder, question,
 * chip, phrase and code (`docs/reference/BadaBhai_Manufacturing_Taxonomy_and_
 * Question_Pack_v2.md`, added by #2994): departments are the 11 of pack
 * section 2, ladders and confirmed/higher-price rungs are the sheet header
 * rows, level keys are the sheet Q2 keys (deepened forms keep their live key,
 * #3000 §4), posting keys follow the #3005 rule, and NCO codes are pack
 * section 13.1 minus the named do-not-bind tokens. Fields transcribed from
 * today's live lists (POSTING_TRADES, TRADE_LEVEL_PACKS, match skills, family
 * bindings) are byte-identical to those lists; the tests below refuse drift.
 *
 * `LOADED_WAVE` gates every check: 0 for the 16 live trades today, raised by
 * one in the same change that loads each wave (#3008 step 9). Entries above the
 * loaded wave are data only — present so waves have something to check, not yet
 * checked. Their `relatedTo` pairs land in MATCH_SKILL_RELATION_PAIRS with
 * #3001, their families and bindings with the wave issues.
 */
export interface TradeCatalogueLadderRung {
  /** The stored/closed rung key. */
  readonly rung: string;
  /** The label this trade shows for the rung. */
  readonly label: string;
}

export interface TradeCatalogueEntry {
  /** Pack section 3 code, T01..T60. */
  readonly code: string;
  /** The trade key. */
  readonly roleKind: string;
  /** One of the 11 departments in pack section 2. */
  readonly department: string;
  /** Shop-floor or desk, per the sheet. */
  readonly kind: "shop_floor" | "desk";
  /** live, deepen or new, per pack section 3. */
  readonly status: "live" | "deepen" | "new";
  /** 0 for the 16 live trades, then 1, 2, 3 per wave. */
  readonly wave: 0 | 1 | 2 | 3;
  /** The worker question pack id. */
  readonly packId: string;
  /** The profiling family that owns the pack. */
  readonly familyId: string;
  /** The trade's own match skill id. */
  readonly matchSkillId: string;
  /** Display ladder, lowest rung first. */
  readonly ladder: readonly TradeCatalogueLadderRung[];
  /** First rung that counts as confirmed. */
  readonly confirmedFrom: string;
  /** First rung that prices higher. */
  readonly higherPriceFrom: string;
  /** The pack's level question key. */
  readonly levelKey: string;
  /** Related trade skills (pack section 5; pairs land with #3001). */
  readonly relatedTo: readonly string[];
  /** Ordered question keys a posting of this trade may ask (#3005 rule). */
  readonly postingQuestionKeys: readonly string[];
  /** NCO-2015 codes bound to the family (8-digit, dot form). */
  readonly ncoCodes: readonly string[];
}

