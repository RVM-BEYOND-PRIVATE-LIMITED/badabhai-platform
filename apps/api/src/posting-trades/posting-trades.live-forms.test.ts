import { describe, expect, it } from "vitest";
import type { QuestionPack } from "@badabhai/ai-contracts";
import { loadQuestionPackCorpus } from "@badabhai/db";
import { LIVE_POSTING_TRADE_KINDS } from "@badabhai/taxonomy";
import { toCorpusItem } from "../profiling/corpus-packs.fixture";
import type { PackRegistryService } from "../profiling/pack-registry.service";
import { releaseServiceFor } from "../trade-release/trade-release.test-support";
import { PostingTradesService } from "./posting-trades.service";

/**
 * #3005 — the 16 live posting forms, built from the REAL checked-in pack corpus (each family's
 * active version, exactly what `PackRegistryService` resolves from the seeded rows).
 *
 * The snapshot was taken on the key-ending filter (`isPostingQuestion`) before it was replaced
 * by the explicit `postingQuestionKeys` list, and is never regenerated by that change: the 16
 * forms a company sees must be byte-identical before and after (tracking #3024 rule 3).
 */
const CORPUS = loadQuestionPackCorpus().packs;

const PACKS = new Map<string, QuestionPack | null>();
function activePack(familyId: string): QuestionPack | null {
  if (!PACKS.has(familyId)) {
    const active = CORPUS.filter((p) => p.family_id === familyId && p.status === "active");
    const record = active.length === 1 ? active[0]! : null;
    PACKS.set(
      familyId,
      record === null
        ? null
        : {
            pack_id: record.pack_id,
            version: record.version,
            family_id: record.family_id,
            locale: record.locale ?? "hi-IN",
            status: "active",
            content_hash: `corpus_${record.pack_id}_${record.version}`,
            items: (record.items as unknown as Array<Record<string, unknown>>).map(toCorpusItem),
          },
    );
  }
  return PACKS.get(familyId)!;
}

const packs = {
  loadForFamily: async (familyId: string) => activePack(familyId),
} as unknown as PackRegistryService;

describe("#3005 — the 16 live posting forms over the real pack corpus", () => {
  it("are byte-identical to the forms the key-ending filter built", async () => {
    const forms = await new PostingTradesService(packs, releaseServiceFor()).listForms();
    expect(forms.map((form) => form.role_kind)).toEqual([...LIVE_POSTING_TRADE_KINDS]);
    for (const form of forms) {
      expect(form.questions.length, `${form.role_kind}: its active pack resolved`).toBeGreaterThan(0);
    }
    expect(JSON.stringify(forms, null, 1)).toMatchSnapshot();
  }, 60_000);
});
